def is_os_dark_mode_enabled() -> bool:
    """Best-effort OS app theme detection.

    Windows: reads AppsUseLightTheme from the user theme registry key.
    macOS: reads AppleInterfaceStyle.
    Linux: checks common GTK/GNOME dark-theme hints.
    Unknown/unsupported systems default to light mode.
    """
    system = platform.system().lower()

    if system.startswith("win"):
        try:
            import winreg  # type: ignore

            key_path = r"Software\Microsoft\Windows\CurrentVersion\Themes\Personalize"
            with winreg.OpenKey(winreg.HKEY_CURRENT_USER, key_path) as key:
                value, _type = winreg.QueryValueEx(key, "AppsUseLightTheme")
            return int(value) == 0
        except Exception:
            return False

    if system == "darwin":
        try:
            proc = subprocess.run(
                ["defaults", "read", "-g", "AppleInterfaceStyle"],
                text=True,
                stdout=subprocess.PIPE,
                stderr=subprocess.DEVNULL,
                timeout=2,
            )
            return "dark" in (proc.stdout or "").strip().lower()
        except Exception:
            return False

    # Linux / BSD best effort.
    for env_name in ("GTK_THEME", "QT_STYLE_OVERRIDE", "XDG_CURRENT_DESKTOP"):
        value = os.environ.get(env_name, "")
        if "dark" in value.lower():
            return True

    try:
        proc = subprocess.run(
            ["gsettings", "get", "org.gnome.desktop.interface", "color-scheme"],
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            timeout=2,
        )
        if "dark" in (proc.stdout or "").lower():
            return True
    except Exception:
        pass

    try:
        proc = subprocess.run(
            ["gsettings", "get", "org.gnome.desktop.interface", "gtk-theme"],
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            timeout=2,
        )
        return "dark" in (proc.stdout or "").lower()
    except Exception:
        return False



def _normalize_patch_raw_path(raw: str) -> str:
    raw = (raw or "").strip()
    if not raw:
        return ""
    # Unified diff paths may be followed by timestamps separated by tabs/spaces.
    raw = raw.split("\t", 1)[0].strip()
    if raw.startswith('"') and raw.endswith('"'):
        raw = raw[1:-1]
    return raw.replace("\\", "/")


def _strip_patch_path(raw_path: str, strip_level: int) -> str | None:
    raw_path = _normalize_patch_raw_path(raw_path)
    if not raw_path or raw_path == "/dev/null":
        return None

    # Ignore absolute paths and drive-prefixed paths before stripping.
    if raw_path.startswith("/") or (len(raw_path) >= 3 and raw_path[1:3] == ":/"):
        return None

    parts = [part for part in raw_path.split("/") if part not in ("", ".")]
    if strip_level > 0:
        parts = parts[strip_level:]
    if not parts:
        return None
    if any(part == ".." for part in parts):
        return None
    return "/".join(parts)


def collect_unified_patch_target_paths(patch_path: Path, strip_level: int) -> set[str]:
    """Return target relative paths touched by a unified patch.

    This is intentionally conservative. It is used only for backup creation;
    git apply is still the source of truth for actual patch validation/application.
    """
    touched: set[str] = set()
    old_path: str | None = None

    for line in read_text_safely(patch_path).splitlines():
        if line.startswith("--- "):
            old_path = line[4:].strip()
            continue
        if line.startswith("+++ "):
            new_path = line[4:].strip()
            candidate = new_path if _normalize_patch_raw_path(new_path) != "/dev/null" else old_path
            rel = _strip_patch_path(candidate or "", strip_level)
            if rel:
                touched.add(rel)
            old_path = None

    return touched


def create_patch_backup(root: Path, patch_path: Path, strip_level: int) -> tuple[Path | None, int]:
    touched = collect_unified_patch_target_paths(patch_path, strip_level)
    existing = []
    for rel in sorted(touched, key=str.lower):
        src = root / Path(*rel.split("/"))
        try:
            if src.is_file():
                existing.append((rel, src))
        except OSError:
            pass

    if not existing:
        return None, 0

    backup_root = root / ".dumpit_patch_backup" / datetime.now().strftime("%Y%m%d_%H%M%S")
    for rel, src in existing:
        dst = backup_root / Path(*rel.split("/"))
        ensure_parent_dir(dst)
        shutil.copy2(src, dst)
    return backup_root, len(existing)


def _patch_rel_path(root: Path, rel_posix: str) -> Path:
    return root / Path(*rel_posix.split("/"))


def _collect_patch_preview_rel_paths(patch_path: Path, strip_level: int) -> tuple[str, ...]:
    """Return all relative paths needed to preview a patch application.

    Both old and new side paths are included so rename/delete/create hunks can be
    represented in the before/after visual diff.
    """
    paths: set[str] = set()
    old_path: str | None = None

    for line in read_text_safely(patch_path).splitlines():
        if line.startswith("--- "):
            old_path = line[4:].strip()
            continue
        if line.startswith("+++ "):
            new_path = line[4:].strip()
            for raw in (old_path, new_path):
                rel = _strip_patch_path(raw or "", strip_level)
                if rel:
                    paths.add(rel)
            old_path = None

    # Fallback for unusual patches that expose only diff --git headers or mode changes.
    if not paths:
        for raw in collect_patch_raw_paths(patch_path):
            rel = _strip_patch_path(raw, strip_level)
            if rel:
                paths.add(rel)

    return tuple(sorted(paths, key=str.lower))


def _read_file_for_patch_preview(path: Path) -> str:
    if not path.exists() or not path.is_file():
        raise FileNotFoundError(str(path))

    try:
        size = path.stat().st_size
    except OSError:
        size = -1

    if is_probably_binary(path):
        digest = "unknown"
        try:
            digest = hashlib.sha256(path.read_bytes()).hexdigest()
        except OSError:
            pass
        return f"[[BINARY FILE | size={size} | sha256={digest}]]\n"

    return read_text_safely(path)


def _read_patch_preview_snapshot(root: Path, rel_paths: tuple[str, ...]) -> dict[str, str]:
    files: dict[str, str] = {}
    for rel in rel_paths:
        path = _patch_rel_path(root, rel)
        try:
            if path.is_file():
                files[rel] = _read_file_for_patch_preview(path)
        except OSError:
            continue
    return files


def _prepare_patch_preview_temp_root(root: Path, rel_paths: tuple[str, ...], temp_root: Path) -> None:
    for rel in rel_paths:
        src = _patch_rel_path(root, rel)
        dst = _patch_rel_path(temp_root, rel)
        ensure_parent_dir(dst)
        if src.is_file():
            shutil.copy2(src, dst)


def build_patch_preview_diff(
    *,
    root: Path,
    patch_path: Path,
    strip_level: int,
    reverse: bool,
) -> DumpDiffResult:
    """Build a before/after visual diff for a patch without touching the target root."""
    rel_paths = _collect_patch_preview_rel_paths(patch_path, strip_level)
    if not rel_paths:
        raise ValueError("No file paths were found in this patch.")

    before_files = _read_patch_preview_snapshot(root, rel_paths)

    with tempfile.TemporaryDirectory(prefix="dumpit_patch_preview_") as tmp:
        temp_root = Path(tmp).resolve()
        _prepare_patch_preview_temp_root(root, rel_paths, temp_root)

        ok, output = run_git_apply_patch(
            root=temp_root,
            patch_path=patch_path,
            strip_level=strip_level,
            reverse=reverse,
            check_only=False,
        )
        if not ok:
            raise RuntimeError(output)

        after_files = _read_patch_preview_snapshot(temp_root, rel_paths)

    before = DumpSnapshot(
        source=root / f"__patch_preview_before__{patch_path.name}",
        files=before_files,
    )
    after = DumpSnapshot(
        source=root / f"__patch_preview_after__{patch_path.name}",
        files=after_files,
    )
    return compare_dump_snapshots(before, after)


def run_git_apply_patch(
    *,
    root: Path,
    patch_path: Path,
    strip_level: int,
    reverse: bool,
    check_only: bool,
) -> tuple[bool, str]:
    git = shutil.which("git")
    if not git:
        return False, "git.exe not found in PATH. Install Git for Windows or add git.exe to PATH."

    cmd = [git, "apply"]
    if check_only:
        cmd.append("--check")
    if reverse:
        cmd.append("-R")
    cmd.append(f"-p{strip_level}")
    cmd.append(str(patch_path))

    creationflags = getattr(subprocess, "CREATE_NO_WINDOW", 0) if platform.system().lower().startswith("win") else 0
    proc = subprocess.run(
        cmd,
        cwd=str(root),
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        creationflags=creationflags,
    )
    output = "\n".join(x for x in [proc.stdout.strip(), proc.stderr.strip()] if x)
    if proc.returncode == 0:
        return True, output or "OK"
    return False, output or f"git apply failed with exit code {proc.returncode}"


@dataclass(slots=True, frozen=True)
class PatchApplyPlan:
    root: Path
    strip_level: int
    check_output: str
    attempts: tuple[str, ...]


def _unique_existing_paths(paths: list[Path]) -> list[Path]:
    seen: set[str] = set()
    out: list[Path] = []
    for path in paths:
        try:
            resolved = path.resolve()
        except Exception:
            resolved = path
        key = canon_path(resolved)
        if key in seen or not resolved.exists() or not resolved.is_dir():
            continue
        seen.add(key)
        out.append(resolved)
    return out


def _candidate_patch_roots(profile_root: Path) -> list[Path]:
    # Batch profiles may point either to the repo root or to a source subfolder such as ./app.
    # Try the selected folder first, then a small number of parents.
    candidates = [profile_root]
    parent = profile_root
    for _ in range(3):
        parent = parent.parent
        candidates.append(parent)
    return _unique_existing_paths(candidates)


def _split_diff_git_paths(payload: str) -> list[str]:
    try:
        return shlex.split(payload, posix=True)
    except Exception:
        return payload.split()


def collect_patch_raw_paths(patch_path: Path) -> tuple[str, ...]:
    """Collect raw file paths referenced by a patch header.

    The result is used only to rank and prune cwd/-p auto-detect attempts;
    git apply --check remains the validation source of truth.
    """
    paths: list[str] = []
    for line in read_text_safely(patch_path).splitlines():
        if line.startswith("diff --git "):
            parts = _split_diff_git_paths(line[len("diff --git "):].strip())
            if len(parts) >= 2:
                paths.extend(parts[:2])
            continue
        if line.startswith("--- ") or line.startswith("+++ "):
            paths.append(line[4:].strip())

    out: list[str] = []
    seen: set[str] = set()
    for raw in paths:
        norm = _normalize_patch_raw_path(raw)
        if not norm or norm == "/dev/null" or norm in seen:
            continue
        seen.add(norm)
        out.append(norm)
    return tuple(out)


def collect_patch_side_raw_paths(patch_path: Path, *, side: str) -> tuple[str, ...]:
    if side not in {"old", "new"}:
        raise ValueError("side must be 'old' or 'new'")

    prefix = "--- " if side == "old" else "+++ "
    out: list[str] = []
    seen: set[str] = set()
    for line in read_text_safely(patch_path).splitlines():
        if not line.startswith(prefix):
            continue
        norm = _normalize_patch_raw_path(line[4:].strip())
        if not norm or norm == "/dev/null" or norm in seen:
            continue
        seen.add(norm)
        out.append(norm)
    return tuple(out)


def _patch_has_git_ab_prefix(raw_paths: tuple[str, ...]) -> bool:
    for raw in raw_paths:
        parts = [part for part in _normalize_patch_raw_path(raw).split("/") if part not in ("", ".")]
        if parts and parts[0] in {"a", "b"}:
            return True
    return False


def _strip_level_possible(raw_paths: tuple[str, ...], strip_level: int) -> bool:
    if strip_level < 0:
        return False
    if not raw_paths:
        return True
    # git apply rejects a strip level if it removes every component from even
    # one file header in the patch. Require all usable patch paths to survive.
    return all(_strip_patch_path(raw, strip_level) is not None for raw in raw_paths)


def _candidate_strip_levels(preferred: int, raw_paths: tuple[str, ...] | None = None) -> list[int]:
    raw_paths = raw_paths or ()

    levels: list[int] = []
    # Standard git patches use a/... and b/... headers. For those, -p1 is the
    # correct first probe regardless of a stale/manual value left in the field.
    if _patch_has_git_ab_prefix(raw_paths):
        levels.append(1)

    levels.extend([preferred, 0, 1, 2, 3, 4, 5, 6])

    out: list[int] = []
    for level in levels:
        if level >= 0 and level not in out and _strip_level_possible(raw_paths, level):
            out.append(level)
    return out


def _rel_exists(root: Path, rel_posix: str) -> bool:
    try:
        return (root / Path(*rel_posix.split("/"))).exists()
    except OSError:
        return False


def _rel_parent_exists(root: Path, rel_posix: str) -> bool:
    try:
        return (root / Path(*rel_posix.split("/"))).parent.exists()
    except OSError:
        return False


def _score_patch_candidate(
    *,
    root: Path,
    strip_level: int,
    reference_raw_paths: tuple[str, ...],
    all_raw_paths: tuple[str, ...],
) -> int:
    # Existing reference files are the strongest signal. Parent directories are
    # weaker but useful for patches containing mostly new files.
    existing_score = 0
    for raw in reference_raw_paths:
        rel = _strip_patch_path(raw, strip_level)
        if rel and _rel_exists(root, rel):
            existing_score += 1

    parent_score = 0
    for raw in all_raw_paths:
        rel = _strip_patch_path(raw, strip_level)
        if rel and _rel_parent_exists(root, rel):
            parent_score += 1

    return existing_score * 1000 + parent_score


def _short_first_error(output: str, max_len: int = 220) -> str:
    text = " ".join((output or "").split())
    if not text:
        return "git apply failed"
    return text[:max_len] + ("..." if len(text) > max_len else "")


def detect_git_apply_plan(
    *,
    profile_root: Path,
    patch_path: Path,
    preferred_strip_level: int,
    reverse: bool,
) -> PatchApplyPlan:
    attempts: list[str] = []
    last_error = ""

    raw_paths = collect_patch_raw_paths(patch_path)
    reference_raw_paths = collect_patch_side_raw_paths(patch_path, side="new" if reverse else "old")
    if not reference_raw_paths:
        reference_raw_paths = raw_paths

    roots = _candidate_patch_roots(profile_root)
    levels = _candidate_strip_levels(preferred_strip_level, raw_paths)

    ranked: list[tuple[int, int, int, Path, int]] = []
    for root_index, root in enumerate(roots):
        for level_index, strip_level in enumerate(levels):
            if not _strip_level_possible(raw_paths, strip_level):
                continue
            score = _score_patch_candidate(
                root=root,
                strip_level=strip_level,
                reference_raw_paths=reference_raw_paths,
                all_raw_paths=raw_paths,
            )
            # Higher score first. root_index and level_index preserve stable fallback order.
            ranked.append((-score, root_index, level_index, root, strip_level))

    if not ranked:
        raise RuntimeError("No valid strip level can be derived from this patch header.")

    ranked.sort()

    best_failed_score = -1
    best_failed_root: Path | None = None
    best_failed_strip_level: int | None = None
    best_failed_output = ""

    for neg_score, _root_index, _level_index, root, strip_level in ranked:
        score = -neg_score
        ok, output = run_git_apply_patch(
            root=root,
            patch_path=patch_path,
            strip_level=strip_level,
            reverse=reverse,
            check_only=True,
        )
        marker = "OK" if ok else "FAIL"
        attempts.append(f"{marker} cwd={root} -p{strip_level} score={score}: {_short_first_error(output)}")
        if ok:
            return PatchApplyPlan(root=root, strip_level=strip_level, check_output=output, attempts=tuple(attempts))
        last_error = output
        if score > best_failed_score:
            best_failed_score = score
            best_failed_root = root
            best_failed_strip_level = strip_level
            best_failed_output = output

    detail = "\n".join(attempts[-12:])
    if best_failed_score > 0 and best_failed_root is not None and best_failed_strip_level is not None:
        raise RuntimeError(
            "Patch path resolved, but git apply --check failed. "
            f"Best candidate: cwd={best_failed_root} -p{best_failed_strip_level} score={best_failed_score}. "
            "This usually means the patch is stale, already partly applied, or the target files differ from the patch base. "
            f"Last error: {_short_first_error(best_failed_output or last_error, 500)}"
            + ("\nAttempts:\n" + detail if detail else "")
        )

    raise RuntimeError(
        "No valid cwd/-p combination found. Last error: "
        f"{_short_first_error(last_error, 500)}"
        + ("\nAttempts:\n" + detail if detail else "")
    )


def enable_windows_file_drop(widget: tk.Widget, callback: Callable[[list[str]], None]) -> object | None:
    """Enable best-effort Windows Explorer file drop for a Tk widget/window.

    Tkinter has no portable native file drop. This uses WM_DROPFILES on Windows only.
    It is optional and safely returns None if unavailable.
    """
    if not platform.system().lower().startswith("win"):
        return None

    try:
        import ctypes
        from ctypes import wintypes

        widget.update_idletasks()
        hwnd = widget.winfo_id()
        if not hwnd:
            return None

        WM_DROPFILES = 0x0233
        GWL_WNDPROC = -4
        LRESULT = ctypes.c_ssize_t
        WNDPROC = ctypes.WINFUNCTYPE(LRESULT, wintypes.HWND, wintypes.UINT, wintypes.WPARAM, wintypes.LPARAM)

        user32 = ctypes.windll.user32
        shell32 = ctypes.windll.shell32

        if ctypes.sizeof(ctypes.c_void_p) == 8:
            SetWindowLongPtr = user32.SetWindowLongPtrW
            SetWindowLongPtr.argtypes = [wintypes.HWND, ctypes.c_int, ctypes.c_void_p]
            SetWindowLongPtr.restype = ctypes.c_void_p
            CallWindowProc = user32.CallWindowProcW
            CallWindowProc.argtypes = [ctypes.c_void_p, wintypes.HWND, wintypes.UINT, wintypes.WPARAM, wintypes.LPARAM]
            CallWindowProc.restype = LRESULT
        else:
            SetWindowLongPtr = user32.SetWindowLongW
            SetWindowLongPtr.argtypes = [wintypes.HWND, ctypes.c_int, ctypes.c_void_p]
            SetWindowLongPtr.restype = ctypes.c_void_p
            CallWindowProc = user32.CallWindowProcW
            CallWindowProc.argtypes = [ctypes.c_void_p, wintypes.HWND, wintypes.UINT, wintypes.WPARAM, wintypes.LPARAM]
            CallWindowProc.restype = LRESULT

        shell32.DragAcceptFiles.argtypes = [wintypes.HWND, wintypes.BOOL]
        shell32.DragAcceptFiles.restype = None
        shell32.DragQueryFileW.argtypes = [wintypes.HANDLE, wintypes.UINT, wintypes.LPWSTR, wintypes.UINT]
        shell32.DragQueryFileW.restype = wintypes.UINT
        shell32.DragFinish.argtypes = [wintypes.HANDLE]
        shell32.DragFinish.restype = None

        old_proc = ctypes.c_void_p()

        def _wndproc(hwnd_, msg, wparam, lparam):
            if msg == WM_DROPFILES:
                paths: list[str] = []
                try:
                    count = shell32.DragQueryFileW(wparam, 0xFFFFFFFF, None, 0)
                    for i in range(count):
                        length = shell32.DragQueryFileW(wparam, i, None, 0)
                        buf = ctypes.create_unicode_buffer(length + 1)
                        shell32.DragQueryFileW(wparam, i, buf, length + 1)
                        if buf.value:
                            paths.append(buf.value)
                finally:
                    shell32.DragFinish(wparam)
                if paths:
                    widget.after(0, lambda ps=paths: callback(ps))
                return 0
            return CallWindowProc(old_proc.value, hwnd_, msg, wparam, lparam)

        new_proc = WNDPROC(_wndproc)
        old = SetWindowLongPtr(hwnd, GWL_WNDPROC, ctypes.cast(new_proc, ctypes.c_void_p))
        if not old:
            return None
        old_proc.value = old
        shell32.DragAcceptFiles(hwnd, True)
        return {"hwnd": hwnd, "old_proc": old_proc, "new_proc": new_proc}
    except Exception:
        return None


def parse_csv_list(s: str) -> list[str]:
    return [x.strip() for x in s.split(",") if x.strip()]


def normalize_patterns(patterns: list[str]) -> list[str]:
    out: list[str] = []
    for p in patterns:
        p = p.strip()
        if not p:
            continue
        if p.startswith(".") and "*" not in p and "/" not in p and "\\" not in p:
            out.append(f"*{p.lower()}")
        else:
            out.append(p.lower())
    return out



def normalize_ui_path(p: str) -> str:
    """Normalize a path string for the current OS (fixes Tk forward slashes on Windows)."""
    p = (p or "").strip()
    if not p:
        return p
    return os.path.normpath(p)


def canon_path(p: Path) -> str:
    """Canonical path string for comparisons (case-insensitive on Windows)."""
    return os.path.normcase(os.path.normpath(str(p)))


def rel_posix(root: Path, file_path: Path) -> str:
    return file_path.relative_to(root).as_posix()


def should_skip_by_dir(rel_path: Path, exclude_dirs: set[str]) -> bool:
    return any(part.lower() in exclude_dirs for part in rel_path.parts)


def is_probably_binary(p: Path) -> bool:
    try:
        with p.open("rb") as f:
            chunk = f.read(8192)
        return b"\x00" in chunk
    except Exception:
        return True


def read_text_safely(p: Path) -> str:
    for enc in ("utf-8-sig", "utf-8"):
        try:
            return p.read_text(encoding=enc)
        except UnicodeDecodeError:
            pass
    return p.read_text(encoding="utf-8", errors="replace")


def matches_any(rel_path_posix: str, name: str, patterns: list[str]) -> bool:
    rp = rel_path_posix.lower()
    nm = name.lower()
    for pat in patterns:
        if ("/" in pat) or ("\\" in pat):
            if fnmatch.fnmatch(rp, pat.replace("\\", "/")):
                return True
        else:
            if fnmatch.fnmatch(nm, pat):
                return True
    return False


def collect_files(root: Path, exclude_dirs: set[str], patterns: list[str], skip_binary: bool, exclude_files: Optional[Set[str]] = None) -> list[Path]:
    files: list[Path] = []
    exclude_files = exclude_files or set()
    for p in root.rglob("*"):
        if p.is_dir():
            continue

        # Avoid including the output file itself (can cause huge/infinite-looking exports)
        if exclude_files and canon_path(p) in exclude_files:
            continue
        rel = p.relative_to(root)
        if should_skip_by_dir(rel, exclude_dirs):
            continue

        rp = rel.as_posix()
        if not matches_any(rp, p.name, patterns):
            continue

        if skip_binary and is_probably_binary(p):
            continue

        files.append(p)

    files.sort(key=lambda x: str(x).lower())
    return files


def strip_output_timestamp_from_stem(stem: str) -> str:
    match = TIMESTAMP_STEM_RE.match(stem or "")
    if match:
        return match.group("base")
    return stem


def build_default_output(root: Path, add_ts: bool = False) -> Path:
    path = root / f"{root.name}.txt"
    if add_ts:
        return add_timestamp_to_output_path(path)
    return path


def get_output_base_path(path: Path) -> Path:
    stem = strip_output_timestamp_from_stem(path.stem)
    return path.with_name(f"{stem}{path.suffix}")


def add_timestamp_to_output_path(path: Path, now: datetime | None = None) -> Path:
    base = get_output_base_path(path)
    ts = (now or datetime.now()).strftime(TIMESTAMP_FORMAT)
    return base.with_name(f"{base.stem}_{ts}{base.suffix}")


def resolve_export_output_path(root: Path, raw_output_file: str, add_timestamp: bool) -> Path:
    raw_output_file = normalize_ui_path(raw_output_file or "")
    base_path = Path(raw_output_file).resolve() if raw_output_file else build_default_output(root, False)
    if add_timestamp:
        return add_timestamp_to_output_path(base_path)
    return base_path


def timestamped_output_regex(base_path: Path) -> re.Pattern[str]:
    base = get_output_base_path(base_path)
    return re.compile(
        r"^"
        + re.escape(base.stem)
        + r"_(?P<ts>\d{4}-\d{2}-\d{2}_\d{6})"
        + re.escape(base.suffix)
        + r"$"
    )


def collect_timestamped_output_files(path: Path) -> list[Path]:
    base = get_output_base_path(path)
    regex = timestamped_output_regex(base)
    try:
        children = list(base.parent.iterdir())
    except OSError:
        return []

    files: list[Path] = []
    for child in children:
        try:
            if child.is_file() and regex.match(child.name):
                files.append(child)
        except OSError:
            continue
    return files


def build_output_exclude_files(out_path: Path, add_timestamp: bool) -> set[str]:
    exclude_files = {canon_path(out_path)}
    if add_timestamp:
        base = get_output_base_path(out_path)
        exclude_files.add(canon_path(base))
        exclude_files.update(canon_path(path) for path in collect_timestamped_output_files(base))
    return exclude_files


def parse_timestamp_keep_old_value(raw: str, default: str = DEFAULT_TIMESTAMP_KEEP_OLD) -> int:
    value = (raw or "").strip()
    if not value:
        value = default
    try:
        parsed = int(value)
    except ValueError:
        raise ValueError("Max old timestamped exports to keep must be an integer.") from None
    if parsed < 0:
        raise ValueError("Max old timestamped exports to keep must be 0 or greater.")
    return parsed


def cleanup_old_timestamped_outputs(out_path: Path, keep_old_count: int) -> tuple[int, int]:
    keep_old_count = max(0, int(keep_old_count))
    regex = timestamped_output_regex(out_path)
    candidates: list[tuple[str, int, Path]] = []

    for path in collect_timestamped_output_files(out_path):
        match = regex.match(path.name)
        if not match:
            continue
        try:
            mtime_ns = path.stat().st_mtime_ns
        except OSError:
            mtime_ns = 0
        candidates.append((match.group("ts"), mtime_ns, path))

    # Keep the newest export plus N older timestamped exports.
    candidates.sort(key=lambda item: (item[0], item[1], item[2].name.lower()), reverse=True)
    keep_total = keep_old_count + 1
    deleted = 0
    failed = 0
    for _ts, _mtime_ns, path in candidates[keep_total:]:
        try:
            path.unlink()
            deleted += 1
        except OSError:
            failed += 1
    return deleted, failed


@dataclass(slots=True)
class ExportFileEntry:
    path: Path
    rel_path: str
    header_path: str
    text: str
    line_count: int
    modified_at: str


def format_file_mtime(p: Path) -> str:
    try:
        return datetime.fromtimestamp(p.stat().st_mtime).strftime("%Y-%m-%d %H:%M:%S")
    except Exception:
        return "unknown"


def count_lines(text: str) -> int:
    if not text:
        return 0
    return text.count("\n") + (0 if text.endswith("\n") else 1)


def collect_export_entries(
    root: Path,
    exclude_dirs: set[str],
    patterns: list[str],
    skip_binary: bool,
    header_full_path: bool,
    exclude_files: Optional[Set[str]] = None,
) -> tuple[list[ExportFileEntry], int]:
    files = collect_files(root, exclude_dirs, patterns, skip_binary, exclude_files=exclude_files)
    entries: list[ExportFileEntry] = []
    skipped = 0

    for p in files:
        try:
            text = read_text_safely(p)
        except Exception:
            skipped += 1
            continue

        rel_path = rel_posix(root, p)
        header_path = str(p) if header_full_path else rel_path
        entries.append(
            ExportFileEntry(
                path=p,
                rel_path=rel_path,
                header_path=header_path,
                text=text,
                line_count=count_lines(text),
                modified_at=format_file_mtime(p),
            )
        )

    return entries, skipped


def build_project_tree(entries: list[ExportFileEntry]) -> str:
    tree: dict[str, dict] = {}

    for entry in entries:
        parts = entry.rel_path.split("/")
        node = tree
        for part in parts[:-1]:
            node = node.setdefault(part + "/", {})
        node[parts[-1]] = entry

    lines: list[str] = []

    def walk(node: dict[str, dict | ExportFileEntry], depth: int) -> None:
        names = sorted(node.keys(), key=lambda name: (0 if name.endswith("/") else 1, name.lower()))
        for name in names:
            value = node[name]
            indent = "  " * depth
            if isinstance(value, ExportFileEntry):
                lines.append(
                    f"{indent}{name} [lines: {value.line_count} | modified: {value.modified_at}]"
                )
            else:
                lines.append(f"{indent}{name}")
                walk(value, depth + 1)

    walk(tree, 0)
    return "\n".join(lines)


def render_export_text(
    root: Path,
    out_path: Path,
    profile_name: str,
    entries: list[ExportFileEntry],
) -> str:
    parts: list[str] = []
    timestamp_utc = datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")
    project_tree = build_project_tree(entries)

    parts.append("===== DUMPIT EXPORT =====\n")
    parts.append(f"timestamp_utc: {timestamp_utc}\n")
    parts.append(f"root: {root}\n")
    parts.append(f"output: {out_path}\n")
    parts.append(f"profile: {profile_name}\n")
    parts.append(f"files_included: {len(entries)}\n")
    parts.append("\n")

    parts.append("===== PROJECT TREE =====\n")
    if project_tree:
        parts.append(project_tree)
        parts.append("\n")
    else:
        parts.append("[[NO FILES INCLUDED]]\n")
    parts.append("\n")

    for entry in entries:
        parts.append(
            f"===== FILE: {entry.header_path} | lines={entry.line_count} | modified={entry.modified_at} =====\n"
        )
        parts.append(entry.text)
        if not parts[-1].endswith("\n"):
            parts.append("\n")
        parts.append("\n")

    return "".join(parts)


def export_to_file(
    root: Path,
    out_path: Path,
    exclude_dirs: set[str],
    patterns: list[str],
    skip_binary: bool,
    header_full_path: bool,
    profile_name: str = "Default",
    exclude_files: Optional[Set[str]] = None,
) -> tuple[int, int]:
    if exclude_files is None:
        exclude_files = {canon_path(out_path)}
    else:
        exclude_files = set(exclude_files)
        exclude_files.add(canon_path(out_path))
    entries, skipped = collect_export_entries(
        root=root,
        exclude_dirs=exclude_dirs,
        patterns=patterns,
        skip_binary=skip_binary,
        header_full_path=header_full_path,
        exclude_files=exclude_files,
    )

    content = render_export_text(
        root=root,
        out_path=out_path,
        profile_name=profile_name,
        entries=entries,
    )

    ensure_parent_dir(out_path)
    out_path.write_text(content, encoding="utf-8")
    return (len(entries), skipped)


def sanitize_profile_name(name: str) -> str:
    name = (name or "").strip()
    name = name.replace("\n", " ").replace("\r", " ").strip()
    # evita caratteri “problematici” per sezioni ini
    for bad in [":", "[", "]"]:
        name = name.replace(bad, "-")
    return name


DUMP_FILE_HEADER_PREFIX = "===== FILE: "
DUMP_FILE_HEADER_SUFFIX = " ====="
DUMP_ROOT_PREFIX = "root:"
WINDOWS_DRIVE_PATH_RE = re.compile(r"^[A-Za-z]:[\\/]")


@dataclass(slots=True)
class DumpSnapshot:
    source: Path
    files: dict[str, str]


@dataclass(slots=True, frozen=True)
class DumpImportEntry:
    source_header_path: str
    rel_path: str
    target_path: Path
    text: str
    exists: bool
    action: str


@dataclass(slots=True, frozen=True)
class DumpImportSkippedEntry:
    source_header_path: str
    reason: str


@dataclass(slots=True)
class DumpImportPlan:
    dump_path: Path
    target_root: Path
    source_root: str
    entries: tuple[DumpImportEntry, ...]
    skipped: tuple[DumpImportSkippedEntry, ...]

    @property
    def create_count(self) -> int:
        return sum(1 for entry in self.entries if entry.action == "create")

    @property
    def overwrite_count(self) -> int:
        return sum(1 for entry in self.entries if entry.action == "overwrite")

    @property
    def skip_existing_count(self) -> int:
        return sum(1 for entry in self.entries if entry.action == "skip_existing")

    @property
    def write_count(self) -> int:
        return self.create_count + self.overwrite_count

    @property
    def total_count(self) -> int:
        return len(self.entries) + len(self.skipped)


@dataclass(slots=True, frozen=True)
class DumpImportResult:
    created: int
    overwritten: int
    skipped_existing: int
    skipped_invalid: int
    backed_up: int
    backup_root: Path | None

    @property
    def written(self) -> int:
        return int(self.created) + int(self.overwritten)


@dataclass(slots=True)
class DumpDiffResult:
    old: DumpSnapshot
    new: DumpSnapshot
    added: list[str]
    removed: list[str]
    modified: list[str]
    unchanged: list[str]

    @property
    def changed_count(self) -> int:
        return len(self.added) + len(self.removed) + len(self.modified)


def _extract_dump_file_header(line: str) -> Optional[str]:
    raw = line.rstrip("\n").rstrip("\r")
    if not (raw.startswith(DUMP_FILE_HEADER_PREFIX) and raw.endswith(DUMP_FILE_HEADER_SUFFIX)):
        return None

    inner = raw[len(DUMP_FILE_HEADER_PREFIX):-len(DUMP_FILE_HEADER_SUFFIX)]
    # Current DumpIt headers are: path | lines=N | modified=...
    # Older dumps are: path
    for marker in (" | lines=", " | modified="):
        if marker in inner:
            inner = inner.split(marker, 1)[0]
            break
    inner = inner.strip()
    return inner or None


def parse_dump_text(source: Path, text: str) -> DumpSnapshot:
    files: dict[str, str] = {}
    current_path: str | None = None
    current_lines: list[str] = []

    def flush_current() -> None:
        nonlocal current_path, current_lines
        if current_path is None:
            return
        # DumpIt writes one blank separator line after every file. Remove that separator.
        if current_lines and current_lines[-1] == "\n":
            current_lines = current_lines[:-1]
        files[current_path] = "".join(current_lines)
        current_lines = []

    for line in text.splitlines(keepends=True):
        header_path = _extract_dump_file_header(line)
        if header_path is not None:
            flush_current()
            current_path = header_path
            current_lines = []
        elif current_path is not None:
            current_lines.append(line)

    flush_current()

    if not files:
        raise ValueError(f"No DumpIt file sections found in: {source}")
    return DumpSnapshot(source=source, files=files)



def extract_dump_root_from_text(text: str) -> str:
    for line in text.splitlines():
        raw = line.strip()
        if raw.startswith(DUMP_ROOT_PREFIX):
            return raw[len(DUMP_ROOT_PREFIX):].strip()
        if raw.startswith(DUMP_FILE_HEADER_PREFIX):
            break
    return ""


def _normalize_dump_path_string(raw: str) -> str:
    value = str(raw or "").strip()
    if value.startswith('"') and value.endswith('"'):
        value = value[1:-1]
    return value.replace("\\", "/").strip()


def _is_absolute_dump_path(raw: str) -> bool:
    value = _normalize_dump_path_string(raw)
    return bool(
        value.startswith("/")
        or value.startswith("//")
        or value.startswith("\\")
        or WINDOWS_DRIVE_PATH_RE.match(value)
    )


def _dump_header_path_to_relative(header_path: str, dump_root: str) -> tuple[str | None, str]:
    raw = _normalize_dump_path_string(header_path)
    root = _normalize_dump_path_string(dump_root).rstrip("/")

    if root:
        raw_cmp = raw.lower()
        root_cmp = root.lower()
        if raw_cmp == root_cmp:
            return None, "header path points to dump root, not to a file"
        if raw_cmp.startswith(root_cmp + "/"):
            raw = raw[len(root):].lstrip("/")

    if _is_absolute_dump_path(raw):
        return None, "absolute path is outside or not relative to dump root"

    while raw.startswith("./"):
        raw = raw[2:]

    parts = [part for part in raw.split("/") if part not in {"", "."}]
    if not parts:
        return None, "empty relative path"
    if any(part == ".." for part in parts):
        return None, "path traversal is not allowed"
    if any("\x00" in part for part in parts):
        return None, "path contains NUL byte"
    if any(":" in part for part in parts):
        return None, "path contains unsupported ':' character"

    return "/".join(parts), ""


def build_dump_import_plan(
    *,
    dump_path: Path,
    target_root: Path,
    overwrite_existing: bool,
) -> DumpImportPlan:
    dump_text = read_text_safely(dump_path)
    snapshot = parse_dump_text(dump_path, dump_text)
    source_root = extract_dump_root_from_text(dump_text)

    entries: list[DumpImportEntry] = []
    skipped: list[DumpImportSkippedEntry] = []
    seen_rel_paths: set[str] = set()

    for header_path, content in snapshot.files.items():
        rel_path, reason = _dump_header_path_to_relative(header_path, source_root)
        if not rel_path:
            skipped.append(DumpImportSkippedEntry(source_header_path=header_path, reason=reason or "invalid path"))
            continue

        rel_key = rel_path.lower()
        if rel_key in seen_rel_paths:
            skipped.append(DumpImportSkippedEntry(source_header_path=header_path, reason=f"duplicate dump path after normalization: {rel_path}"))
            continue
        seen_rel_paths.add(rel_key)

        target_path = target_root.joinpath(*rel_path.split("/"))
        try:
            exists = target_path.exists()
            if exists and target_path.is_dir():
                skipped.append(DumpImportSkippedEntry(source_header_path=header_path, reason=f"target path is an existing directory: {rel_path}"))
                continue
        except OSError as exc:
            skipped.append(DumpImportSkippedEntry(source_header_path=header_path, reason=f"target path cannot be checked: {exc}"))
            continue

        action = "create"
        if exists:
            action = "overwrite" if overwrite_existing else "skip_existing"

        entries.append(
            DumpImportEntry(
                source_header_path=header_path,
                rel_path=rel_path,
                target_path=target_path,
                text=content,
                exists=bool(exists),
                action=action,
            )
        )

    return DumpImportPlan(
        dump_path=dump_path,
        target_root=target_root,
        source_root=source_root,
        entries=tuple(entries),
        skipped=tuple(skipped),
    )


def execute_dump_import_plan(
    plan: DumpImportPlan,
    *,
    overwrite_existing: bool,
    backup_overwritten: bool,
) -> DumpImportResult:
    created = 0
    overwritten = 0
    skipped_existing = 0
    backed_up = 0
    backup_root: Path | None = None

    if backup_overwritten and any(entry.action == "overwrite" for entry in plan.entries):
        backup_root = plan.target_root / ".dumpit_import_backup" / datetime.now().strftime("%Y%m%d_%H%M%S")

    for entry in plan.entries:
        if entry.action == "skip_existing":
            skipped_existing += 1
            continue

        exists = entry.target_path.exists()
        if exists and not overwrite_existing:
            skipped_existing += 1
            continue
        if exists and entry.target_path.is_dir():
            continue

        if exists and backup_root is not None:
            backup_path = backup_root.joinpath(*entry.rel_path.split("/"))
            ensure_parent_dir(backup_path)
            shutil.copy2(entry.target_path, backup_path)
            backed_up += 1

        ensure_parent_dir(entry.target_path)
        entry.target_path.write_text(entry.text, encoding="utf-8")
        if exists:
            overwritten += 1
        else:
            created += 1

    return DumpImportResult(
        created=created,
        overwritten=overwritten,
        skipped_existing=skipped_existing,
        skipped_invalid=len(plan.skipped),
        backed_up=backed_up,
        backup_root=backup_root,
    )


def compare_dump_snapshots(old: DumpSnapshot, new: DumpSnapshot) -> DumpDiffResult:
    old_paths = set(old.files)
    new_paths = set(new.files)
    added = sorted(new_paths - old_paths, key=str.lower)
    removed = sorted(old_paths - new_paths, key=str.lower)
    common = sorted(old_paths & new_paths, key=str.lower)
    modified = [p for p in common if old.files[p] != new.files[p]]
    unchanged = [p for p in common if old.files[p] == new.files[p]]
    return DumpDiffResult(old=old, new=new, added=added, removed=removed, modified=modified, unchanged=unchanged)


def load_dump_diff(old_path: Path, new_path: Path) -> DumpDiffResult:
    old = parse_dump_text(old_path, read_text_safely(old_path))
    new = parse_dump_text(new_path, read_text_safely(new_path))
    return compare_dump_snapshots(old, new)


def _split_patch_lines(text: str) -> list[str]:
    # Dump exports normalize file boundaries; patch output is therefore line-normalized.
    return text.splitlines()


def _unified_patch_chunk(old_text: str, new_text: str, fromfile: str, tofile: str) -> str:
    lines = difflib.unified_diff(
        _split_patch_lines(old_text),
        _split_patch_lines(new_text),
        fromfile=fromfile,
        tofile=tofile,
        lineterm="",
    )
    chunk = "\n".join(lines)
    return (chunk + "\n") if chunk else ""


def build_unified_patch(diff: DumpDiffResult) -> str:
    chunks: list[str] = []
    for path in diff.removed:
        chunks.append(_unified_patch_chunk(diff.old.files[path], "", f"a/{path}", "/dev/null"))

    for path in diff.added:
        chunks.append(_unified_patch_chunk("", diff.new.files[path], "/dev/null", f"b/{path}"))

    for path in diff.modified:
        chunks.append(_unified_patch_chunk(diff.old.files[path], diff.new.files[path], f"a/{path}", f"b/{path}"))

    chunks = [chunk for chunk in chunks if chunk]
    return "\n".join(chunks) if chunks else "# DumpIt delta: no differences found.\n"


def build_delta_text(diff: DumpDiffResult) -> str:
    parts: list[str] = []
    parts.append("===== DUMPIT DELTA =====\n")
    parts.append(f"created_utc: {datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S UTC')}\n")
    parts.append(f"old_dump: {diff.old.source}\n")
    parts.append(f"new_dump: {diff.new.source}\n")
    parts.append(f"added: {len(diff.added)}\n")
    parts.append(f"removed: {len(diff.removed)}\n")
    parts.append(f"modified: {len(diff.modified)}\n")
    parts.append(f"unchanged: {len(diff.unchanged)}\n\n")

    if not diff.changed_count:
        parts.append("No differences found.\n")
        return "".join(parts)

    if diff.added:
        parts.append("===== ADDED FILES =====\n")
        for path in diff.added:
            parts.append(f"+ {path}\n")
        parts.append("\n")

    if diff.removed:
        parts.append("===== REMOVED FILES =====\n")
        for path in diff.removed:
            parts.append(f"- {path}\n")
        parts.append("\n")

    if diff.modified:
        parts.append("===== MODIFIED FILES =====\n")
        for path in diff.modified:
            parts.append(f"* {path}\n")
        parts.append("\n")

    if diff.added:
        for path in diff.added:
            parts.append(f"===== ADDED FILE: {path} =====\n")
            parts.append(diff.new.files[path])
            if not parts[-1].endswith("\n"):
                parts.append("\n")
            parts.append("\n")

    if diff.removed:
        for path in diff.removed:
            parts.append(f"===== REMOVED FILE: {path} =====\n")
            parts.append(diff.old.files[path])
            if not parts[-1].endswith("\n"):
                parts.append("\n")
            parts.append("\n")

    if diff.modified:
        parts.append("===== UNIFIED DIFF =====\n")
        parts.append(build_unified_patch(diff))
        if not parts[-1].endswith("\n"):
            parts.append("\n")

    return "".join(parts)


def _diff_anchor(path: str) -> str:
    return "file-" + hashlib.sha1(path.encode("utf-8", errors="replace")).hexdigest()[:16]


def _html_escape(text: str) -> str:
    return html_lib.escape(text, quote=False)


def _render_html_diff_table(old_text: str, new_text: str) -> str:
    old_lines = old_text.splitlines()
    new_lines = new_text.splitlines()
    matcher = difflib.SequenceMatcher(None, old_lines, new_lines)
    rows: list[str] = []

    for tag, i1, i2, j1, j2 in matcher.get_opcodes():
        old_count = i2 - i1
        new_count = j2 - j1
        row_count = max(old_count, new_count)
        css = {
            "equal": "eq",
            "delete": "del",
            "insert": "ins",
            "replace": "chg",
        }.get(tag, "chg")

        for offset in range(row_count):
            old_index = i1 + offset
            new_index = j1 + offset
            has_old = old_index < i2
            has_new = new_index < j2
            old_no = str(old_index + 1) if has_old else ""
            new_no = str(new_index + 1) if has_new else ""
            old_line = _html_escape(old_lines[old_index]) if has_old else ""
            new_line = _html_escape(new_lines[new_index]) if has_new else ""
            rows.append(
                "<tr class='{css}'>"
                "<td class='ln'>{old_no}</td><td class='code old'>{old_line}</td>"
                "<td class='ln'>{new_no}</td><td class='code new'>{new_line}</td>"
                "</tr>".format(css=css, old_no=old_no, old_line=old_line, new_no=new_no, new_line=new_line)
            )

    if not rows:
        rows.append("<tr class='eq'><td></td><td class='code'>No line differences.</td><td></td><td></td></tr>")

    return "<table class='diff-table'><tbody>" + "\n".join(rows) + "</tbody></table>"


def _render_file_block(diff: DumpDiffResult, status: str, path: str) -> str:
    safe_path = _html_escape(path)
    anchor = _diff_anchor(path)
    badge_class = status.lower()

    if status == "ADDED":
        table = _render_html_diff_table("", diff.new.files[path])
    elif status == "REMOVED":
        table = _render_html_diff_table(diff.old.files[path], "")
    else:
        table = _render_html_diff_table(diff.old.files[path], diff.new.files[path])

    return f"""
<section id="{anchor}" class="file-block" data-path="{html_lib.escape(path.lower())}" data-status="{badge_class}">
  <div class="file-head">
    <span class="badge {badge_class}">{status}</span>
    <h2>{safe_path}</h2>
  </div>
  {table}
</section>
"""


